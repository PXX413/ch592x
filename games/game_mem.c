/**************************************************************************
 * game_mem.c —— "用时申请、走时释放"的临时内存
 *
 * 只有一块位置，同一时刻只能有一个所有者。见 game_mem.h 的说明。
 **************************************************************************/

#include "game_mem.h"
#include <stdlib.h>

/*==========================================================================
 * 状态
 *========================================================================*/
static void    *s_ptr;              /* 当前所有者的指针，0 = 没人用 */
static uint16_t s_bytes_sz;         /* 记着大小，便于测试和调试 */

/*==========================================================================
 * 对外
 *========================================================================*/
void *GameMem_Acquire(uint16_t bytes)
{
    if (bytes == 0u)
    {
        return 0;
    }

    if (s_ptr != 0)
    {
        return 0;                   /* 已经有人占着：必须先用完还回来 */
    }

    s_ptr = malloc((size_t)bytes);
    if (s_ptr == 0)
    {
        s_bytes_sz = 0u;
        return 0;                   /* 堆不够：调用方自己降级 */
    }

    s_bytes_sz = bytes;
    return s_ptr;
}

void GameMem_Yield(void *p)
{
    if (p == 0)
    {
        return;
    }

    /* 只放"当前所有者"的内存：传别人的指针不会把别人的块放掉 */
    if (p != s_ptr)
    {
        return;
    }

    free(s_ptr);
    s_ptr      = 0;
    s_bytes_sz = 0u;
}

bool GameMem_Busy(void)
{
    return (s_ptr != 0);
}

uint16_t GameMem_Bytes(void)
{
    return s_bytes_sz;
}

