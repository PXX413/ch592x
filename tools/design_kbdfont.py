# ================= 预览 =================
def raster(ch, W=32, H=40):
    assert ch in G, ch
    adv, polys = G[ch]
    sc = 1.0/140.0
    bm = [[0]*W for _ in range(H)]
    def P(x, y):
        return int(x*W*sc*1.35), int(y*H*sc)
    for p in polys:
        for k in range(0, len(p)-2, 2):
            x0,y0,x1,y1 = p[k],p[k+1],p[k+2],p[k+3]
            ax,ay = P(x0,y0); bx,by = P(x1,y1)
            dx=abs(bx-ax); dy=-abs(by-ay)
            sx=1 if ax<bx else -1; sy=1 if ay<by else -1
            err=dx+dy
            while True:
                if 0<=ay<H and 0<=ax<W: bm[ay][ax]=1
                if ax==bx and ay==by: break
                e2=2*err
                if e2>=dy: err+=dy; ax+=sx
                if e2<=dx: err+=dx; ay+=sy
    return bm

